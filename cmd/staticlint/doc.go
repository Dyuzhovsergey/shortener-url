// Package main содержит multichecker staticlint — набор статических анализаторов,
// запускаемых одной командой.
//
// # Запуск
//
// 1) Быстрый запуск без сборки бинаря:
//
//	go run ./cmd/staticlint ./...
//
// 2) Сборка бинаря и запуск:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// # Аргументы
//
// multichecker принимает список пакетов/паттернов так же, как go tool vet.
// Например:
//
//	./staticlint ./internal/...
//	./staticlint ./cmd/shortener
//
// # Что проверяет multichecker
//
// staticlint состоит из нескольких групп анализаторов:
//
// 1) Анализаторы из пакета golang.org/x/tools/go/analysis/passes (vet-подобные).
//
//   - assign      — находит бессмысленные присваивания (когда результат не используется).
//   - atomic      — проверяет корректность использования sync/atomic.
//   - bools       — ищет подозрительные выражения с bool.
//   - buildtag    — проверяет корректность build-тегов.
//   - cgocall     — проверяет потенциально опасные вызовы cgo.
//   - composite   — предупреждает о неинициализированных ключах в литералах и похожих ошибках.
//   - copylock    — предупреждает о копировании значений с embedded mutex.
//   - errorsas    — проверяет корректность использования errors.As.
//   - httpresponse— проверяет, что http.Response.Body закрывается.
//   - loopclosure — выявляет ошибки захвата переменных цикла в замыканиях.
//   - lostcancel  — проверяет, что context.CancelFunc вызывается.
//   - nilfunc     — ищет сравнения функций с nil в подозрительных местах.
//   - printf      — проверяет форматные строки fmt.Printf/Printf-подобных функций.
//   - shift       — проверяет корректность битовых сдвигов.
//   - stdmethods  — проверяет сигнатуры стандартных методов (например, String()).
//   - structtag   — проверяет корректность struct-тегов.
//   - unmarshal   — проверяет корректность вызовов json/xml unmarshal.
//   - unreachable — находит недостижимый код.
//   - unsafeptr   — проверяет подозрительные преобразования unsafe.Pointer.
//   - unusedresult— проверяет игнорирование результатов некоторых функций.
//
// 2) Все анализаторы класса SA из staticcheck (honnef.co/go/tools/staticcheck).
//
// Эти анализаторы (SAxxxx) — большая группа правил, находящих реальные баги:
// неверные сравнения, потенциальные паники, неправильные условия, ошибки
// при работе со слайсами/мапами, контекстами и т.п.
//
// 3) Минимум один анализатор из других классов staticcheck.
//
// В staticlint включён:
//   - ST1000 — проверяет наличие package comment (godoc) у пакетов.
//
// 4) Публичные анализаторы “со стороны”.
//
//   - ineffassign (github.com/gordonklaus/ineffassign) — находит неэффективные присваивания,
//     когда значение переменной тут же перезатирается до использования.
//   - bodyclose (github.com/timakin/bodyclose) — проверяет, что HTTP response body закрывается.
//
// 5) Собственный анализатор проекта.
//
//   - noosexitmain — запрещает прямой вызов os.Exit внутри func main() пакета main
//     в модулях проекта. Логику следует выносить в отдельную функцию (например, run())
//     и возвращать ошибку, а завершение процесса делать через логгер/обработку ошибок.
